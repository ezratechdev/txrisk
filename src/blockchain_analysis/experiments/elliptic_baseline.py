"""Phase 1 baseline: licit vs illicit on the Elliptic dataset.

Trains each baseline model on each feature set, scores it on held-out data, and writes
reports/elliptic_baseline.md plus a .json file with the raw numbers.

    python -m blockchain_analysis.experiments.elliptic_baseline
"""

from __future__ import annotations

import argparse
import json
import time

import numpy as np
import pandas as pd

from blockchain_analysis.data.elliptic import FEATURE_SETS, load_elliptic
from blockchain_analysis.evaluation.metrics import evaluate, f1_by_group
from blockchain_analysis.evaluation.splits import Split, random_split, temporal_split
from blockchain_analysis.models.baselines import baseline_models
from blockchain_analysis.paths import REPORTS_DIR

TRAIN_UNTIL = 34  # Weber et al. train on time steps 1-34 and test on 35-49.

COLUMN_NAMES = {
    "model": "Model",
    "features": "Features",
    "precision": "Precision",
    "recall": "Recall",
    "f1": "F1",
    "pr_auc": "PR-AUC",
    "roc_auc": "ROC-AUC",
    "recall_at_1pct_fpr": "Recall @1% FPR",
    "brier": "Brier",
    "ece": "ECE",
    "fit_seconds": "Fit (s)",
}


def run_split(
    labeled: pd.DataFrame, split: Split, seed: int
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Returns one row of metrics per (model, feature set) and illicit F1 per test time step."""
    y = labeled["label"].to_numpy(dtype=int)
    time_step = labeled["time_step"].to_numpy()
    rows, per_step = [], {}
    for feature_set, columns in FEATURE_SETS.items():
        X = labeled[columns].to_numpy(dtype=np.float32)
        for model_name, make_model in baseline_models(seed).items():
            start = time.perf_counter()
            model = make_model().fit(X[split.train], y[split.train])
            prob = model.predict_proba(X[split.test])[:, 1]
            metrics = evaluate(y[split.test], prob)
            rows.append({"model": model_name, "features": feature_set, **metrics,
                         "fit_seconds": time.perf_counter() - start})
            per_step[f"{model_name} ({feature_set})"] = f1_by_group(
                y[split.test], prob, time_step[split.test]
            )
            print(f"  {split.name.split()[0]:8} {model_name:20} {feature_set:5} "
                  f"F1={metrics['f1']:.3f} PR-AUC={metrics['pr_auc']:.3f}")
    return pd.DataFrame(rows), pd.DataFrame(per_step)


def markdown_table(frame: pd.DataFrame) -> str:
    def cell(value: object) -> str:
        if isinstance(value, float):
            return "–" if np.isnan(value) else f"{value:.3f}"
        return str(value)

    lines = ["| " + " | ".join(map(str, frame.columns)) + " |",
             "|" + "|".join("---" for _ in frame.columns) + "|"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |"
              for row in frame.itertuples(index=False)]
    return "\n".join(lines)


def write_report(labeled: pd.DataFrame, n_total: int, results: dict[str, pd.DataFrame],
                 per_step: pd.DataFrame, seed: int) -> None:
    n_illicit = int(labeled["label"].sum())
    temporal, random_ = (results[k].rename(columns=COLUMN_NAMES) for k in ("temporal", "random"))
    per_step = per_step.rename_axis("Time step").reset_index()
    report = f"""# Elliptic baseline

Generated by `python -m blockchain_analysis.experiments.elliptic_baseline --seed {seed}`.

Data: {len(labeled):,} labelled transactions ({n_illicit:,} illicit, {n_illicit / len(labeled):.1%})
out of {n_total:,}. Transactions with unknown labels are left out of training and scoring.

Precision, recall and F1 are for the illicit class at a 0.5 threshold. "Recall @1% FPR" is the
share of illicit transactions caught while flagging at most 1% of licit ones. Brier and ECE
measure calibration (lower is better).

## Temporal split: train on time steps 1–{TRAIN_UNTIL}, test on {TRAIN_UNTIL + 1}–49

This is the result that matters. For reference, Weber et al. (2019) report illicit F1 of 0.788
for a random forest on all features and 0.628 for a graph convolutional network on this split.

{markdown_table(temporal)}

## Random split, same test size (for comparison only)

The difference from the table above is how much a random split overstates performance.

{markdown_table(random_)}

## Illicit F1 by test time step (temporal split)

Weber et al. found that every model breaks down from time step 43, when a large dark
market was shut down.

{markdown_table(per_step)}
"""
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "elliptic_baseline.md").write_text(report, encoding="utf-8")
    raw = {name: frame.to_dict("records") for name, frame in results.items()}
    raw["per_time_step_f1"] = per_step.to_dict("records")
    (REPORTS_DIR / "elliptic_baseline.json").write_text(
        json.dumps(raw, indent=2, allow_nan=True), encoding="utf-8"
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args(argv)

    data = load_elliptic()
    labeled = data.labeled
    temporal = temporal_split(labeled["time_step"], TRAIN_UNTIL)
    random_ = random_split(len(labeled), temporal.test.mean(), seed=args.seed)

    results, per_step = {}, None
    for key, split in (("temporal", temporal), ("random", random_)):
        results[key], step_f1 = run_split(labeled, split, args.seed)
        if key == "temporal":
            per_step = step_f1
    write_report(labeled, len(data.txs), results, per_step, args.seed)
    print(f"Report written to {REPORTS_DIR / 'elliptic_baseline.md'}")


if __name__ == "__main__":
    main()
