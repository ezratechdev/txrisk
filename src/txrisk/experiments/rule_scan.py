"""Phase 3: run the deterministic rules over extracted days.

Each day is loaded, scanned and released, so memory stays flat over any range. Hits are
written to data/processed/rule_hits.parquet, which is both the rule engine's output and
the raw material for the labels the models will train on.

    python -m txrisk.experiments.rule_scan
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from txrisk.data.ethereum import extracted_days, load_day
from txrisk.data.labels import load_labels
from txrisk.paths import PROCESSED_DIR, RAW_DIR
from txrisk.report import markdown_table, save_report
from txrisk.rules import empty_hits
from txrisk.rules.approvals import decode_approvals, find_approval_phishing
from txrisk.rules.drains import approval_pairs, find_token_drains
from txrisk.rules.exposure import find_known_bad_exposure
from txrisk.rules.poisoning import find_address_poisoning


def known_bad_addresses() -> dict[str, str]:
    """Known-bad Ethereum addresses mapped to the source and reason that listed them."""
    try:
        labels = load_labels()
    except FileNotFoundError:
        print("  no labels found; run python -m txrisk.data.labels to enable exposure checks")
        return {}
    ethereum = labels[labels["chain"] == "ethereum"]
    return {
        row.address: f"{row.source} ({row.fraud_type}, {row.reference})"
        for row in ethereum.itertuples()
    }


def scan_day(
    day: str, known_bad: dict[str, str], root: Path = RAW_DIR / "ethereum"
) -> pd.DataFrame:
    transfers = load_day(
        "token_transfers", day, ["from_address", "to_address", "value", "transaction_hash"], root
    )
    approvals = load_day(
        "approvals", day, ["address", "topics", "transaction_hash"], root
    )
    contracts = load_day("contracts", day, ["address"], root)
    transactions = load_day(
        "transactions", day, ["from_address", "to_address", "hash"], root
    ).rename(columns={"hash": "transaction_hash"})
    eth_transfers = load_day(
        "eth_transfers", day, ["to_address", "value", "transaction_hash"], root
    )
    # What can corroborate a drain: the collector is brand new, or already reported.
    corroborating = set(contracts["address"].dropna()) | set(known_bad)
    approved = approval_pairs(decode_approvals(approvals))

    hits = [
        find_address_poisoning(transfers, day),
        find_approval_phishing(approvals, contracts, day, token_transfers=transfers),
        find_token_drains(transfers, transactions, day, approved, eth_transfers, corroborating),
        find_known_bad_exposure(transactions, known_bad, day),
        find_known_bad_exposure(transfers, known_bad, day),
    ]
    return pd.concat([h for h in hits if not h.empty], ignore_index=True) if any(
        not h.empty for h in hits
    ) else empty_hits()


def summarise(hits: pd.DataFrame) -> pd.DataFrame:
    if hits.empty:
        return pd.DataFrame(columns=["rule", "role", "confidence", "hits", "addresses"])
    return (
        hits.groupby(["rule", "role", "confidence"])
        .agg(hits=("address", "size"), addresses=("address", "nunique"))
        .reset_index()
    )


def build_report(hits: pd.DataFrame, days: list[str], examples: pd.DataFrame) -> str:
    return f"""# Rule scan

Generated by `python -m txrisk.experiments.rule_scan` over {len(days)} day(s):
{days[0]} to {days[-1]}.

Rules are deterministic: every hit below can be checked by hand against the chain. They
run before any model, and their output doubles as training labels, since reported-scam
lists are far too small to learn from.

## Hits

{markdown_table(summarise(hits))}

## Examples

{markdown_table(examples)}

## Reading these

- `address_poisoning` names both sides. The **victim** is the account whose history was
  poisoned and did nothing wrong; only the **attacker** row is evidence of fraud. Mixing
  the two would teach a model that victims are criminals.
- `approval_phishing` only considers spender contracts deployed inside the scanned
  window. Without that, it returns the busiest trading routers on the chain. Its hits are
  **candidates** until tokens are seen moving from the approving wallets into the
  spender: a protocol that launched this morning looks identical until then.
- `known_bad_exposure` is limited by what has been reported: it finds nothing on a day
  when no listed address is active, which is most days.
"""


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--days", nargs="*", help="days to scan (default: all extracted)")
    args = parser.parse_args(argv)

    days = args.days or extracted_days()
    known_bad = known_bad_addresses()
    print(f"scanning {len(days)} day(s) against {len(known_bad):,} known-bad addresses")

    all_hits = []
    for day in days:
        hits = scan_day(day, known_bad)
        all_hits.append(hits)
        counts = hits.groupby("rule").size().to_dict() if not hits.empty else {}
        print(f"  {day}: {len(hits):,} hits {counts}")

    hits = pd.concat(all_hits, ignore_index=True) if all_hits else empty_hits()
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    hits.to_parquet(PROCESSED_DIR / "rule_hits.parquet", index=False)

    examples = (
        hits[hits["role"] != "victim"]
        .drop_duplicates(subset=["rule"])
        .head(10)[["rule", "address", "evidence"]]
        if not hits.empty
        else pd.DataFrame(columns=["rule", "address", "evidence"])
    )
    report = build_report(hits, days, examples)
    print(f"\n{len(hits):,} hits written to {PROCESSED_DIR / 'rule_hits.parquet'}")
    print(f"Report written to {save_report('rule_scan', report, {'hits': len(hits)})}")


if __name__ == "__main__":
    main()
